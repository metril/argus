import { makeCookie, type Cookie } from '../model';
import { fixDomain, parseExpiry } from './loose';
import { stripBom, type Codec, type ParsedRow } from './types';

const HTTP_ONLY = '#HttpOnly_';
const HEADER = '# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by Argus. Edit at your own risk.\n\n';

const upper = (s: string | undefined) => (s ?? '').trim().toUpperCase();

function exportNetscape(cookies: Cookie[]): string {
  const lines = cookies.map((c) => {
    const host = c.domain.replace(/^\./, '');
    const exp = c.session || c.expirationDate === undefined ? 0 : Math.floor(c.expirationDate);
    const f = [c.hostOnly ? host : '.' + host, c.hostOnly ? 'FALSE' : 'TRUE', c.path, c.secure ? 'TRUE' : 'FALSE', String(exp), c.name, c.value];
    return (c.httpOnly ? HTTP_ONLY : '') + f.join('\t');
  });
  return HEADER + lines.join('\n') + (lines.length ? '\n' : '');
}

function parseLine(line: string, row: number): ParsedRow | undefined {
  let s = line.replace(/\r$/, '');
  let httpOnly = false;
  if (s.startsWith(HTTP_ONLY)) { httpOnly = true; s = s.slice(HTTP_ONLY.length); }
  else if (s.trim() === '' || s.trimStart().startsWith('#')) return undefined;
  if (s.trim() === '') return undefined;
  let f = s.split('\t');
  if (f.length < 6) {
    // Pasted through something that turned the tabs into spaces.
    const parts = s.trim().split(/\s+/);
    f = parts.length >= 7 ? [...parts.slice(0, 6), parts.slice(6).join(' ')] : parts;
  }
  if (f.length < 6) return { row, error: 'A cookies.txt line needs seven tab-separated fields.' };
  const flag = upper(f[1]);
  const secure = upper(f[3]);
  if (!['TRUE', 'FALSE'].includes(flag) || !['TRUE', 'FALSE'].includes(secure)) return { row, error: 'The subdomain and secure fields must be TRUE or FALSE.' };
  const domain = (f[0] ?? '').trim();
  if (!domain) return { row, error: 'This line has no domain.' };
  if (!/^-?\d+(\.\d+)?$/.test((f[4] ?? '').trim())) return { row, error: 'The expiry field must be a number of seconds.' };
  const exp = parseExpiry(f[4]);
  const hostOnly = flag === 'FALSE';
  const cookie = makeCookie({
    domain: fixDomain(domain, hostOnly), hostOnly, path: (f[2] ?? '/').trim() || '/', secure: secure === 'TRUE', httpOnly,
    name: f[5] ?? '', value: f[6] ?? '', session: exp === undefined, ...(exp !== undefined ? { expirationDate: exp } : {}),
  });
  if (!cookie.name) return { row, error: 'This line has no cookie name.' };
  return { row, cookie };
}

export const netscape: Codec = {
  id: 'netscape',
  label: 'Netscape cookies.txt',
  extension: 'txt',
  mime: 'text/plain',
  export: exportNetscape,
  parse(text) {
    const out: ParsedRow[] = [];
    stripBom(text).split('\n').forEach((l, i) => { const r = parseLine(l, i + 1); if (r) out.push(r); });
    return out;
  },
};
